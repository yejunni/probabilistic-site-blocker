// config.js
// 확률·시간과 관련된 모든 설정값을 모아두는 파일.
// 숫자를 바꾸고 싶으면 다른 파일은 열지 말고 여기만 고치면 된다.

const CONFIG = {
  // ── 테스트 모드 ────────────────────────────────────────────────
  // true  : 차단 화면 아래에 경과 시간·사용량을 강제로 바꾸는 칸이 나온다
  // false : 그 칸이 사라지고, 강제로 바꾸는 요청도 무시된다
  //
  // 확률을 조정하는 동안에는 켜두고, 제출할 때 false로 바꾸면 된다.
  // 코드를 지울 필요 없이 이 한 줄만 고치면 된다.
  devMode: true,

  // ── 어떤 곡선을 쓸지 고르는 스위치 ──────────────────────────────
  // 'log'     : 초반에 확 오르고 나중엔 완만해짐
  // 'linear'  : 일정한 속도로 직선처럼 오름
  // 'scurve'  : 초반엔 천천히, 중간에 급하게, 끝에 다시 완만 (S자 모양)
  // 'points'  : 아래 points에 찍은 점들을 매끄럽게 이어서 만든 곡선
  //
  // 기본은 'points'다. 설정 화면에서 그래프를 직접 끌어 모양을 만드는 방식이
  // 숫자를 맞춰보는 것보다 직관적이라서.
  curve: 'points',

  // ── scurve(S자 곡선)를 쓸 때만 의미 있는 값 ────────────────────
  midpoint: 60,        // 확률이 대략 절반쯤 되는 시점(분). 클수록 곡선이 오른쪽으로 밀림
  steepness: 0.05,     // 가운데 구간이 얼마나 가파른지. 클수록 계단처럼 급해짐

  // ── log(로그 곡선)를 쓸 때만 의미 있는 값 ──────────────────────
  // "anchorMinutes분에 anchorProb%가 되도록" 곡선 높이를 자동으로 맞춘다.
  anchorMinutes: 80,   // 기준이 되는 시점(분)
  anchorProb: 50,      // 그 시점에서 나왔으면 하는 확률(%)
  smoothness: 30,      // 초반 상승을 얼마나 부드럽게 할지. 작을수록 초반에 급하게 오름

  // ── linear(직선)를 쓸 때만 의미 있는 값 ────────────────────────
  linearFullMin: 150,  // 이 시점(분)에 상한(maxProb)에 도달하도록 기울기를 맞춤

  // ── points(점 잇기)를 쓸 때만 의미 있는 값 ─────────────────────
  // x = 경과 시간(분), y = 그 시점의 확률(%).
  // 이 점들 사이를 매끄러운 곡선으로 이어서 확률을 구한다.
  //
  // 규칙:
  //   - 설정 화면에서는 x를 고정하고 y만 위아래로 끈다.
  //     시간대는 그대로 두고 "그 시점에 몇 %인지"만 정하는 편이 다루기 쉽다
  //   - 0분은 목록에 없어도 항상 0%로 친다. 기다리지 않았으면 확률도 없어야 한다
  //   - 마지막 점 이후는 마지막 y값이 계속 유지된다
  points: [
    { x: 10,  y: 3  },
    { x: 30,  y: 14 },
    { x: 45,  y: 29 },
    { x: 60,  y: 48 },
    { x: 80,  y: 72 },
    { x: 120, y: 85 }
  ],

  // ── 곡선 종류와 상관없이 항상 적용되는 값 ──────────────────────
  maxProb: 85,         // 확률 상한(%). 아무리 오래 기다려도 이 값을 넘지 않는다
  dailyLimit: 60,      // 하루 총 이용 한도(분)

  // 이용 시간 선택지(durationOptions)는 없앴다.
  // 차단 화면에서 +/- 버튼으로 1분 ~ 남은 한도 사이를 직접 정하게 바뀌었다.

  // 오늘 많이 썼을수록 확률을 깎는 강도.
  //   0   = 안 깎음 (오늘 사용 시간이 확률에 전혀 영향을 주지 않음)
  //   0.5 = 한도를 다 썼을 때 확률이 절반이 됨
  //   1   = 한도를 다 썼을 때 확률이 0이 됨
  //
  // 0으로 둔 이유: 확률은 '얼마나 기다렸는지'만 보게 하려는 것.
  // 오늘 얼마나 썼는지는 dailyLimit(남은 한도)으로만 제한한다.
  // 한도가 0이 되면 판정 자체를 안 하므로 그걸로 충분하다.
  usagePenalty: 0

  // 거부 후 대기(cooldownSec)는 없앴다.
  // 거부되면 경과 시간이 0으로 초기화되고, 모든 곡선은 0분에서 정확히 0%다.
  // 그래서 연타해도 "난수 < 0"은 절대 참이 되지 않아 대기를 걸 이유가 없었다.
};
